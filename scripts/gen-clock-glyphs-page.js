#!/usr/bin/env node
// scripts/gen-clock-glyphs-page.js — the settings page's copy of the watch's clock digits:
// writes src/pkjs/page/layout/clock-glyphs.generated.js from what the watch itself draws them
// with, so the Watchface tab's watch preview (preview-watch.js) prints the clock in the
// watch's own glyphs, at the watch's own place:
//   resources/img/clock-<face>-<n>~<platform>.png  each glyph's image (alpha only), inlined
//   src/c/layers/clock_glyphs_metrics.h            each glyph's ink width, left bearing, advance
//   src/c/layers/clock_glyphs_ink.h                each face's ink height (every image's height)
//   src/c/layers/clock_ink.c                       each face's centre offset in its clock band
//   scripts/clock-glyphs-system.json               the 1-bit system fonts' digits (LECO, and the
//                                                  B/W watches' Roboto and Bitham), read out of
//                                                  the SDK's firmware by extract-system-clock-glyphs.py
// The first three are themselves generated by scripts/gen-clock-glyphs.py; run this script
// after it, after the extractor, and after changing clock_ink.c. test/clock-glyphs-page.test.js
// fails while the committed module and these sources disagree.
// Usage: node scripts/gen-clock-glyphs-page.js [--check]
'use strict';
var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var OUT = path.join(ROOT, 'src/pkjs/page/layout/clock-glyphs.generated.js');
var FACES = ['roboto', 'bitham'];
var PLATFORMS = ['basalt', 'emery'];
var GLYPH_COUNT = 11;   // '0'..'9', then ':'

/**
 * The C source of one of the inputs.
 * @param {string} rel Path from the repo root.
 * @returns {string}
 */
function source(rel) {
    return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

/**
 * The part of a C file between `#if defined(<macro>)` / `#elif defined(<macro>)` / `#ifdef
 * <macro>` and the next preprocessor branch.
 * @param {string} src C source.
 * @param {RegExp} start Where the branch opens.
 * @returns {string}
 */
function branch(src, start) {
    var at = src.search(start);
    if (at < 0) { throw new Error('gen-clock-glyphs-page: no branch ' + start); }
    var rest = src.slice(at).replace(start, '');
    var end = rest.search(/^#(elif|else|endif)/m);
    return end < 0 ? rest : rest.slice(0, end);
}

/**
 * Each face's glyph metrics on one platform (clock_glyphs_metrics.h).
 * @param {string} platform 'basalt' | 'emery'.
 * @returns {Object<string, Array<Array<number>>>} Face -> [[w, lsb, adv] per glyph].
 */
function metrics(platform) {
    var part = branch(source('src/c/layers/clock_glyphs_metrics.h'),
        new RegExp('^#(?:el)?if defined\\(PBL_PLATFORM_' + platform.toUpperCase() + '\\)', 'm'));
    var out = {};
    FACES.forEach(function (face) {
        var m = new RegExp('CLOCK_GLYPHS_' + face.toUpperCase() + '\\[CLOCK_GLYPH_COUNT\\] = \\{([\\s\\S]*?)\\};').exec(part);
        if (!m) { throw new Error('gen-clock-glyphs-page: no ' + face + ' table for ' + platform); }
        var rows = [], re = /\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}/g, g;
        while ((g = re.exec(m[1]))) { rows.push([+g[1], +g[2], +g[3]]); }
        if (rows.length !== GLYPH_COUNT) { throw new Error('gen-clock-glyphs-page: ' + face + '/' + platform + ' has ' + rows.length + ' glyphs'); }
        out[face] = rows;
    });
    return out;
}

/**
 * Each face's ink height on one platform (clock_glyphs_ink.h).
 * @param {string} platform 'basalt' | 'emery'.
 * @returns {Object<string, number>} Face -> rows.
 */
function inkHeights(platform) {
    var part = branch(source('src/c/layers/clock_glyphs_ink.h'),
        new RegExp('^#(?:el)?if defined\\(PBL_PLATFORM_' + platform.toUpperCase() + '\\)', 'm'));
    var out = {};
    FACES.forEach(function (face) {
        var m = new RegExp('#define CLOCK_GLYPHS_' + face.toUpperCase() + '_INK_H (\\d+)').exec(part);
        if (!m) { throw new Error('gen-clock-glyphs-page: no ' + face + ' ink height for ' + platform); }
        out[face] = +m[1];
    });
    return out;
}

/**
 * Each time font's ClockInk row on one screen family (clock_ink.c): its centre offset, and the
 * ink height the 1-bit faces seat with (the glyph faces' is clock_glyphs_ink.h's).
 * @param {boolean} emery The emery arm, else the 144 px one.
 * @returns {Object<string, {centreOff: number, inkH: ?number, inkHBw: ?number}>} Font -> row.
 */
function clockInk(emery) {
    var src = source('src/c/layers/clock_ink.c');
    var at = src.indexOf('#ifdef PBL_PLATFORM_EMERY'), mid = src.indexOf('#else', at), end = src.indexOf('#endif', mid);
    if (at < 0 || mid < 0 || end < 0) { throw new Error('gen-clock-glyphs-page: clock_ink.c lost its emery arm'); }
    var part = emery ? src.slice(at, mid) : src.slice(mid, end), out = {};
    ['roboto', 'leco', 'bitham'].forEach(function (font) {
        var m = new RegExp('\\[TIME_FONT_' + font.toUpperCase() + '\\]\\s*=\\s*\\{\\s*(-?\\d+),\\s*([^}]*)\\}').exec(part);
        if (!m) { throw new Error('gen-clock-glyphs-page: no ' + font + ' row in clock_ink.c'); }
        var h = m[2].trim(), lit = /^(\d+)$/.exec(h), ifColor = /PBL_IF_COLOR_ELSE\([^,]+,\s*(\d+)\)/.exec(h);
        out[font] = { centreOff: +m[1], inkH: lit ? +lit[1] : null, inkHBw: ifColor ? +ifColor[1] : (lit ? +lit[1] : null) };
    });
    return out;
}

/**
 * The module's text.
 * @returns {string}
 */
function build() {
    var system = JSON.parse(source('scripts/clock-glyphs-system.json')).fonts;
    var data = { faces: {}, ink: { 0: clockInk(false), 1: clockInk(true) }, system: {} };
    Object.keys(system).sort().forEach(function (name) {
        var f = system[name];
        data.system[name] = { inkTop: f.inkTop, inkH: f.inkH, glyphs: f.glyphs };
    });
    PLATFORMS.forEach(function (platform, f) {
        var met = metrics(platform), inkH = inkHeights(platform);
        data.faces[f] = {};
        FACES.forEach(function (face) {
            data.faces[f][face] = { inkH: inkH[face], glyphs: met[face].map(function (m, n) {
                var png = fs.readFileSync(path.join(ROOT, 'resources/img', 'clock-' + face + '-' + n + '~' + platform + '.png'));
                return m.concat([png.toString('base64')]);
            }) };
        });
    });
    return '// GENERATED by scripts/gen-clock-glyphs-page.js — do not edit; re-run the script.\n'
        + '// ES5, WebView (+ Node for tests). The watch\'s clock digits for the settings page\'s watch\n'
        + '// preview (preview-watch.js): per screen family (0 = 144 px, from basalt\'s glyphs; 1 = emery)\n'
        + '// and face, the ink height and each glyph \'0\'..\'9\', \':\' as [ink width, left bearing,\n'
        + '// advance, its PNG in base64]; per family and time font, the ClockInk row clock_ink.c\n'
        + '// seats the band with (centreOff; inkH where a literal, inkHBw the 1-bit faces\' height);\n'
        + '// and the 1-bit system fonts by name, each glyph [width, height, left, top, advance, PNG],\n'
        + '// top in rows below the line top, inkTop/inkH the digits\' union ink rows.\n'
        + '(function () {\n'
        + '    var CLOCK_GLYPHS = ' + JSON.stringify(data) + ';\n'
        + '    if (typeof module !== \'undefined\' && module.exports) { module.exports = CLOCK_GLYPHS; }\n'
        + '    if (typeof window !== \'undefined\') { window.ClockGlyphs = CLOCK_GLYPHS; }\n'
        + '})();\n';
}

if (require.main === module) {
    var text = build();
    if (process.argv.indexOf('--check') >= 0) {
        var same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === text;
        console.log(same ? 'clock-glyphs.generated.js is current' : 'clock-glyphs.generated.js is STALE: run node scripts/gen-clock-glyphs-page.js');
        process.exit(same ? 0 : 1);
    }
    fs.writeFileSync(OUT, text);
    console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + text.length + ' bytes)');
}

module.exports = { build: build, OUT: OUT };

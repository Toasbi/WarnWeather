// Payloads arrive split into categories that map onto screen areas (forecast
// chart, status row, radar). Each category is processed independently and the
// persist setters report real changes, so only the affected layers redraw.

typedef struct {
    SeriesId id;
    uint32_t trend_key;     // MESSAGE_KEY_* (values unchanged)
} SeriesWire;

static bool handle_forecast(DictionaryIterator *iterator, bool *forecast_dirty) {
    Tuple *temp_trend_tuple = dict_find(iterator, MESSAGE_KEY_TEMP_TREND_UINT8);
    Tuple *forecast_start_tuple = dict_find(iterator, MESSAGE_KEY_FORECAST_START);
    Tuple *num_entries_tuple = dict_find(iterator, MESSAGE_KEY_NUM_ENTRIES);
    // Render-ready, already-selected series (PKJS owns the choice). The line
    // styling that used to ride here is settings-derived and now arrives on the
    // Clay message instead — see handle_line_style below.
    Tuple *temp_min_tuple = dict_find(iterator, MESSAGE_KEY_TEMP_MIN);
    Tuple *temp_max_tuple = dict_find(iterator, MESSAGE_KEY_TEMP_MAX);

    if (!(temp_trend_tuple && forecast_start_tuple && num_entries_tuple)) {
        if (temp_trend_tuple || forecast_start_tuple || num_entries_tuple) {
            APP_LOG(APP_LOG_LEVEL_WARNING,
                    "Forecast payload incomplete (temp=%d start=%d entries=%d) — skipping",
                    temp_trend_tuple != NULL,
                    forecast_start_tuple != NULL,
                    num_entries_tuple != NULL);
        }
        return false;
    }

    // NUM_ENTRIES rides a separate tuple from the trend bytes; clamp it to the
    // trend tuple's own length so a skewed count can never size a read past
    // the array (write_data_if_changed memcmp/writes exactly this many bytes).
    int num_entries = (int) num_entries_tuple->value->int32;
    if (num_entries < 0) { num_entries = 0; }
    if (num_entries > (int) temp_trend_tuple->length) {
        num_entries = (int) temp_trend_tuple->length;
    }
#ifdef WW_ENABLE_MEMORY_LOGGING
    APP_LOG(APP_LOG_LEVEL_DEBUG, "MEM|forecast_payload|entries=%d|free=%lu|used=%lu",
            num_entries,
            (unsigned long)heap_bytes_free(),
            (unsigned long)heap_bytes_used());
#endif
    bool changed = false;
    changed |= persist_set_forecast_start((time_t) forecast_start_tuple->value->int32);
    changed |= persist_set_num_entries(num_entries);
    changed |= persist_set_temp_trend((uint8_t*) temp_trend_tuple->value->data, num_entries);
    if (temp_min_tuple) { changed |= persist_set_temp_min((int) temp_min_tuple->value->int32); }
    if (temp_max_tuple) { changed |= persist_set_temp_max((int) temp_max_tuple->value->int32); }

    // MESSAGE_KEY_* are uint32_t globals (generated by the SDK), not
    // compile-time constants, so the table must be initialized at runtime.
    const SeriesWire WIRE[] = {
        { SERIES_SECOND, MESSAGE_KEY_SECONDARY_LINE_TREND_UINT8 },
        { SERIES_THIRD,  MESSAGE_KEY_THIRD_LINE_TREND_UINT8     },
        { SERIES_BARS,   MESSAGE_KEY_BAR_TREND_UINT8            },
    };
    // Render-ready series (trend bytes only) — table-driven.
    // Element count = byte length (1 byte/elem). Empty/missing => count 0,
    // which the per-series setter treats per its own semantics (line/bar keep
    // a 0 count + stale trend; third deletes its key).
    for (unsigned w = 0; w < sizeof(WIRE) / sizeof(WIRE[0]); ++w) {
        Tuple *tt = dict_find(iterator, WIRE[w].trend_key);
        int count = tt ? (int) tt->length : 0;
        changed |= persist_series_set_trend(WIRE[w].id,
                       count ? (uint8_t*) tt->value->data : NULL, count);
    }

    *forecast_dirty |= changed;
    return true;
}

static bool handle_status(DictionaryIterator *iterator, bool *status_dirty, bool *radar_dirty) {
    Tuple *is_sleeping_tuple = dict_find(iterator, MESSAGE_KEY_IS_SLEEPING);

    if (!is_sleeping_tuple) {
        return false;
    }

    bool changed = false;
    const bool sleeping = (bool) is_sleeping_tuple->value->int16;
    changed |= persist_set_is_sleeping(sleeping);
    if (sleeping) {
        // Sleep onset latches the radar area into snooze immediately.
        // The latch is released on the wake transition by the awake check
        // in inbox_received_callback.
        *radar_dirty |= persist_set_radar_snooze(true);
    }

    *status_dirty |= changed;
    return true;
}

static uint32_t status_line_key(int line_id) {
    switch (line_id) {
        case 0: return MESSAGE_KEY_STATUS_LINE_1_UINT8;
        case 1: return MESSAGE_KEY_STATUS_LINE_2_UINT8;
        case 2: return MESSAGE_KEY_STATUS_LINE_3_UINT8;
        default: return MESSAGE_KEY_STATUS_LINE_4_UINT8;
    }
}

static bool handle_status_lines(DictionaryIterator *iterator, bool *status_dirty) {
    bool any = false;
    bool changed = false;
    for (int i = 0; i < STATUS_LINE_COUNT; i++) {
        Tuple *tuple = dict_find(iterator, status_line_key(i));
        if (!tuple) { continue; }
        any = true;
        if (tuple->type != TUPLE_BYTE_ARRAY ||
            !status_line_validate(tuple->value->data, tuple->length)) {
            // Reject atomically; the last good persisted line stays intact.
            APP_LOG(APP_LOG_LEVEL_WARNING,
                    "Status line %d invalid (%u bytes) — skipping", i + 1,
                    (unsigned) tuple->length);
            continue;
        }
        changed |= persist_set_status_line((uint8_t) i, tuple->value->data,
                                           tuple->length);
    }
    *status_dirty |= changed;
    return any;
}

#if defined(WW_THRESHOLD_HIGHLIGHT)
// Packed weather-kind threshold levels — rides the weather message next to the
// packed lines (the phone computes them; the watch has no raw AQI/wind ints).
static bool handle_status_levels(DictionaryIterator *iterator, bool *status_dirty) {
    Tuple *tuple = dict_find(iterator, MESSAGE_KEY_STATUS_LEVELS_UINT8);
    if (!tuple) { return false; }
    if (tuple->type != TUPLE_BYTE_ARRAY || tuple->length < 1) {
        APP_LOG(APP_LOG_LEVEL_WARNING,
                "Status levels tuple malformed (%u bytes) — skipping",
                (unsigned) tuple->length);
        return true;
    }
    // 2 LE bytes since UV joined the weather kinds (bits 8-9); a 1-byte value
    // (older phone JS) still reads correctly as the low byte.
    int levels = tuple->value->data[0];
    if (tuple->length >= 2) { levels |= tuple->value->data[1] << 8; }
    *status_dirty |= persist_set_status_levels(levels);
    return true;
}

// Threshold settings blob — rides the Clay message (enabled bits, colors, and
// the health-kind thresholds the watch compares live values against).
static bool handle_thresholds(DictionaryIterator *iterator, bool *status_dirty) {
    Tuple *tuple = dict_find(iterator, MESSAGE_KEY_CLAY_THRESHOLDS_UINT8);
    if (!tuple) { return false; }
    if (tuple->type != TUPLE_BYTE_ARRAY ||
        !status_threshold_settings_validate(tuple->value->data, tuple->length)) {
        // Reject atomically; the last good persisted blob stays intact.
        APP_LOG(APP_LOG_LEVEL_WARNING,
                "Threshold settings invalid (%u bytes) — skipping",
                (unsigned) tuple->length);
        return true;
    }
    *status_dirty |= persist_set_threshold_settings(tuple->value->data,
                                                    tuple->length);
    return true;
}
#endif  // WW_THRESHOLD_HIGHLIGHT

